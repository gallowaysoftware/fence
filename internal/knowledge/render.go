// FullClaim is one line of var/knowledge/claims.jsonl: the claim with what the later
// stages concluded about it.
type FullClaim struct {
	Claim
	ClusterID  string   `json:"cluster_id,omitempty"`
	Statement  string   `json:"cluster_statement,omitempty"`
	Origins    int      `json:"cluster_origins,omitempty"`
	Confidence string   `json:"confidence,omitempty"`
	Verdict    *Verdict `json:"verdict,omitempty"`
}

func JoinClaims(claims []Claim, clusters []Cluster) []FullClaim {
	byMember := map[string]*Cluster{}
	for i := range clusters {
		for _, m := range clusters[i].Members {
			byMember[m] = &clusters[i]
		}
	}
	out := make([]FullClaim, len(claims))
	for i, c := range claims {
		out[i].Claim = c
		if k := byMember[c.ID]; k != nil {
			out[i].ClusterID, out[i].Statement, out[i].Origins = k.ID, k.Statement, k.Origins
			out[i].Confidence, out[i].Verdict = k.Confidence, k.Verdict
		}
	}
	return out
}

func EncodeJSONL[T any](xs []T) []byte {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	for _, x := range xs {
		_ = enc.Encode(x)
	}
	return buf.Bytes()
}

// Score orders clusters for the digest: verified and owner-backed first, then by voices.
func Score(k Cluster) int {
	s := k.Origins*10 + k.Quality*3
	switch k.Confidence {
	case ConfVerified:
		s += 40
	case ConfOwner:
		s += 60
	case ConfCodeWrong:
		s += 30 // a community belief the code refutes is worth knowing
	case ConfContested:
		s += 15
	}
	if k.Kind == "opinion" {
		s -= 20
	}
	return s
}

// Digest is the curation input for STRATEGY.md: per topic, the strongest clusters with
// confidence, sources and verdicts. It is not the primer; it is what the primer is
// written from.
func Digest(clusters []Cluster, srcs map[string]Source, perTopic int) string {
	byID := map[string]*Cluster{}
	byTopic := map[string][]*Cluster{}
	for i := range clusters {
		k := &clusters[i]
		byID[k.ID] = k
		byTopic[k.Topic] = append(byTopic[k.Topic], k)
	}
	list := make([]Source, 0, len(srcs))
	for _, s := range srcs {
		list = append(list, s)
	}
	keys := SourceKeys(list)
	var b strings.Builder
	b.WriteString("# Knowledge digest (generated)\n\n")
	counts := map[string]int{}
	for _, k := range clusters {
		counts[k.Confidence]++
	}
	fmt.Fprintf(&b, "%d clusters: ", len(clusters))
	for _, c := range []string{ConfVerified, ConfCodeWrong, ConfContested, ConfOwner, ConfMany, ConfSingle} {
		fmt.Fprintf(&b, "%s %d; ", c, counts[c])
	}
	b.WriteString("\n")
	for _, t := range Topics {
		ks := byTopic[t]
		if len(ks) == 0 {
			continue
		}
		sort.SliceStable(ks, func(i, j int) bool { return Score(*ks[i]) > Score(*ks[j]) })
		fmt.Fprintf(&b, "\n## %s (%d clusters)\n", t, len(ks))
		for i, k := range ks {
			if i >= perTopic {
				break
			}
			fmt.Fprintf(&b, "- [%s|%s|%d src|q%d] %s", k.Confidence, k.Kind, k.Origins, k.Quality, k.Statement)
			if len(k.Conditions) > 0 {
				fmt.Fprintf(&b, " {%s}", strings.Join(k.Conditions[:min(3, len(k.Conditions))], "; "))
			}
			if v := k.Verdict; v != nil && v.Verdict != VerdictUnverifiable {
				fmt.Fprintf(&b, " CODE(%s %s: %s)", v.Verdict, v.Method, v.Evidence)
				if v.Value != "" {
					fmt.Fprintf(&b, " value=%s", v.Value)
				}
			}
			for _, c := range k.Contradicts {
				if o := byID[c.ID]; o != nil {
					fmt.Fprintf(&b, " VS(%s: %s)", o.Statement, c.Note)
				}
			}
			fmt.Fprintf(&b, " <%s>\n", sourceRefs(k.Sources, keys, 6))
		}
	}
	return b.String()
}

func sourceRefs(ids []string, keys map[string]string, n int) string {
	var refs []string
	for _, id := range ids {
		if len(refs) >= n {
			refs = append(refs, fmt.Sprintf("+%d", len(ids)-n))
			break
		}
		if k, ok := keys[id]; ok {
			refs = append(refs, k)
		} else {
			refs = append(refs, id)
		}
	}
	return strings.Join(refs, ",")
}

// RenderSystems writes docs/knowledge/SYSTEMS.md.
func RenderSystems(systems []GameSystem, generated string) string {
	var b strings.Builder
	b.WriteString("# Game systems catalogue\n\n")
	b.WriteString("Every system or loop the community material mentions, sorted by how many independent sources talk about it. " +
		"Generated by `make knowledge` (`fenceknow systems`) on " + generated + "; descriptions are model-written from extracted claims, " +
		"main types are the model's pick among the decompiled type names, and coverage is a text match against this repo, so treat " +
		"both as leads to check, not facts.\n\n")
	b.WriteString("Coverage columns: **RE** = mentioned in `docs/re/*.md`; **hooks** = mod features in `compat/hooks*.json` whose hook targets one of the main types or names the system; **strat** = named in `internal/strategy`.\n\n")
	b.WriteString("| System | Src | Claims | What it is / how players use it | Connects to | Main types | RE | Hooks | Strat |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|\n")
	for _, s := range systems {
		var conn []string
		for _, c := range s.Connections {
			conn = append(conn, c.To+" ("+c.Via+")")
		}
		what := s.Description
		if s.PlayerUse != "" {
			what += " — " + s.PlayerUse
		}
		strat := ""
		if s.Coverage.Strategist {
			strat = "yes"
		}
		fmt.Fprintf(&b, "| %s | %d | %d | %s | %s | %s | %s | %s | %s |\n",
			cell(s.Name), s.Origins, s.Claims, cell(what), cell(strings.Join(conn, "; ")),
			cell(strings.Join(s.Types, ", ")), cell(strings.Join(s.Coverage.REDocs, ", ")),
			cell(strings.Join(s.Coverage.Hooks, ", ")), strat)
	}
	return b.String()
}

func cell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", "/"), "\n", " ")
}

// RenderSources writes docs/knowledge/SOURCES.md: every source, whether it was read,
// how many claims it gave, and its strongest contributions.
func RenderSources(srcs []Source, claims []Claim, clusters []Cluster, fetched map[string]FetchResult) string {
	perSrc := map[string]int{}
	for _, c := range claims {
		perSrc[c.SourceID]++
	}
	contrib := map[string][]*Cluster{}
	for i := range clusters {
		k := &clusters[i]
		if k.Kind == "opinion" {
			continue
		}
		for _, s := range k.Sources {
			contrib[s] = append(contrib[s], k)
		}
	}
	byType := map[string][]Source{}
	var types []string
	for _, s := range srcs {
		if _, ok := byType[s.Type]; !ok {
			types = append(types, s.Type)
		}
		byType[s.Type] = append(byType[s.Type], s)
	}
	sort.Strings(types)
	keys := SourceKeys(srcs)
	var b strings.Builder
	b.WriteString("# Sources\n\nCommunity material the knowledge base was built from (`make knowledge`). " +
		"Quality: 4 owner's play, 3 data-mined wiki / developer / long hard-mode runs, 2 player guides and threads, 1 search-bait guide sites. " +
		"Claims = claims extracted; contributions = the most-corroborated non-opinion points it backs (paraphrased). " +
		"Keys (S1…) are what docs/knowledge/STRATEGY.md cites; they are stable while sources.json is unchanged.\n")
	for _, t := range types {
		ss := byType[t]
		sort.SliceStable(ss, func(i, j int) bool { return perSrc[ss[i].ID] > perSrc[ss[j].ID] })
		fmt.Fprintf(&b, "\n## %s (%d)\n\n| Key | Source | By / date | Q | Claims | Contributions |\n|---|---|---|---|---|---|\n", t, len(ss))
		for _, s := range ss {
			title := s.Title
			if title == "" {
				title = s.URL
			}
			by := s.Channel
			if s.Date != "" {
				by = strings.TrimSpace(by + " " + s.Date)
			}
			if s.Duration > 0 {
				by += fmt.Sprintf(" (%d min)", s.Duration/60)
			}
			n := fmt.Sprint(perSrc[s.ID])
			if r, ok := fetched[s.ID]; ok && !r.OK {
				n = "not read: " + truncate(r.Error, 60)
			} else if !ok && perSrc[s.ID] == 0 {
				n = "not fetched"
			}
			ks := contrib[s.ID]
			sort.SliceStable(ks, func(i, j int) bool { return Score(*ks[i]) > Score(*ks[j]) })
			var cs []string
			for _, k := range ks[:min(2, len(ks))] {
				cs = append(cs, truncate(k.Statement, 140))
			}
			fmt.Fprintf(&b, "| %s | [%s](%s) | %s | %d | %s | %s |\n", keys[s.ID], cell(title), s.URL, cell(by), s.Quality, cell(n), cell(strings.Join(cs, " · ")))
		}
	}
	return b.String()
}

// SourceKeys numbers sources S1… in id order, so citations stay short.
func SourceKeys(srcs []Source) map[string]string {
	ids := make([]string, len(srcs))
	for i, s := range srcs {
		ids[i] = s.ID
	}
	sort.Strings(ids)
	keys := make(map[string]string, len(ids))
	for i, id := range ids {
		keys[id] = fmt.Sprintf("S%d", i+1)
	}
	return keys
}
