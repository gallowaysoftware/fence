#!/usr/bin/env python3
"""Each hard route's odds of beating each deadline format, for the strategist's day-0 menu (docs/STREAM.md).

  deadline_odds.py run   [-seed0 8100000] [-seeds 60] [-parallel 16] [-dir var/odds] [-only ROUTE,...] [-reuse DIR]
  deadline_odds.py build [-dir var/odds] [-out internal/agency/deadline_odds.json]

`run` plays every route in sim/lab/scripts/directives/routes/*.json under every hard format with a deadline
(sim/lab/scripts/directives/formats/*.json), through `fenceformat lab -route R` (the format's handicaps laid over
the route and locked, executor only, 1000-day horizon, nice 10), keeping each summary in DIR/<format>/<route>/.
A summary already there is not run again. `-reuse DIR` first copies the ghost band's summaries (ghost_bands.py's
DIR/<route>/<seed>.json, same seeds and horizon) for formats without handicaps: there the format's directives are
the route's own, so those are the same runs. Challenge formats are left out: the day-0 menu is hard only.

`build` writes, per format and route, the buyouts on or before the deadline out of the runs, their Wilson 95 %
interval in percent and the median win day.
"""
import json
import math
import os
import shutil
import subprocess
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
ROUTES = os.path.join(REPO, "sim", "lab", "scripts", "directives", "routes")
FORMATS = os.path.join(REPO, "sim", "lab", "scripts", "directives", "formats")


def flags(argv, defaults):
    out = dict(defaults)
    i = 0
    while i < len(argv):
        k = argv[i].lstrip("-")
        if k not in out or i + 1 >= len(argv):
            sys.exit(f"unknown flag {argv[i]}")
        out[k] = type(defaults[k])(argv[i + 1])
        i += 2
    return out


def routes(only=""):
    names = sorted(f[:-5] for f in os.listdir(ROUTES) if f.endswith(".json"))
    return [n for n in names if not only or n in only.split(",")]


def deadline_formats():
    out = {}
    for f in sorted(os.listdir(FORMATS)):
        if not f.endswith(".json"):
            continue
        with open(os.path.join(FORMATS, f)) as fh:
            d = json.load(fh)
        if d.get("deadline_day") and d.get("difficulty") == "hard" and not d.get("route"):
            out[f[:-5]] = d
    return out


def run(argv):
    o = flags(argv, {"seed0": 8100000, "seeds": 60, "parallel": 16, "dir": "var/odds", "only": "", "reuse": ""})
    subprocess.run(["go", "build", "-o", "bin/fenceformat", "./cmd/fenceformat"], cwd=REPO, check=True)
    for fname, f in deadline_formats().items():
        for name in routes(o["only"]):
            out = os.path.join(o["dir"], fname, name)
            os.makedirs(out, exist_ok=True)
            if o["reuse"] and not f.get("handicaps"):
                for seed in range(o["seed0"] + 1, o["seed0"] + o["seeds"] + 1):
                    src, dst = os.path.join(o["reuse"], name, f"{seed}.json"), os.path.join(out, f"{seed}.json")
                    if os.path.exists(src) and not os.path.exists(dst):
                        shutil.copyfile(src, dst)
            print(f"{fname} {name}", flush=True)
            # fenceformat lab skips a seed whose summary exists and starts nothing while the game runs.
            r = subprocess.run([os.path.join(REPO, "bin", "fenceformat"), "lab", "-route", name, "-seed0", str(o["seed0"]),
                                "-seeds", str(o["seeds"]), "-parallel", str(o["parallel"]), "-out", out, fname],
                               cwd=REPO, capture_output=True, text=True)
            if r.returncode != 0:
                sys.exit(f"{fname} {name}: {r.stderr.strip()}")


def wilson(wins, runs):
    z = 1.96
    n, p = runs, wins / runs
    den = 1 + z * z / n
    mid = (p + z * z / (2 * n)) / den
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return round(100 * max(0, mid - half)), round(100 * min(1, mid + half))


def median(xs):
    xs = sorted(xs)
    n = len(xs)
    if n == 0:
        return 0
    return xs[n // 2] if n % 2 else round((xs[n // 2 - 1] + xs[n // 2]) / 2)


def build(argv):
    o = flags(argv, {"dir": "var/odds", "out": "internal/agency/deadline_odds.json"})
    doc = {
        "_doc": "Each hard route's odds of beating a deadline format: buyouts (cash or mortgage) on or before the deadline "
                "day, executor alone, the format's handicaps laid over the route and locked; Wilson 95 % interval in "
                "percent. Generated by sim/lab/scripts/deadline_odds.py.",
        "formats": {},
    }
    for fname, f in deadline_formats().items():
        rows, seeds = {}, set()
        for name in routes():
            d = os.path.join(o["dir"], fname, name)
            runs = []
            for p in sorted(os.listdir(d)) if os.path.isdir(d) else []:
                if p.endswith(".json") and p[:-5].isdigit():
                    with open(os.path.join(d, p)) as fh:
                        runs.append(json.load(fh))
            if not runs:
                sys.exit(f"no runs for {fname} {name}: run first")
            for r in runs:
                if isinstance(r.get("crash"), str):
                    sys.exit(f"{fname} {name} seed {r['seed']} crashed")
                seeds.add(r["seed"])
            win_days = [r["last_day"] for r in runs
                        if (r.get("game_over") or "").startswith("buyout") and r["last_day"] <= f["deadline_day"]]
            lo, hi = wilson(len(win_days), len(runs))
            rows[name] = {"wins": len(win_days), "runs": len(runs), "lo": lo, "hi": hi, "median_win_day": median(win_days)}
        s = sorted(seeds)
        doc["formats"][fname] = {"deadline_day": f["deadline_day"], "handicaps": f.get("handicaps", []),
                                 "seeds": f"{s[0]}-{str(s[-1])[-3:]}", "routes": rows}
    lines = ["{", f'"_doc": {json.dumps(doc["_doc"])},', '"formats": {']
    for i, (fname, fd) in enumerate(doc["formats"].items()):
        head = {k: v for k, v in fd.items() if k != "routes"}
        lines.append(f"{json.dumps(fname)}: {{" + json.dumps(head)[1:-1] + ', "routes": {')
        names = list(fd["routes"])
        for j, name in enumerate(names):
            sep = "," if j < len(names) - 1 else ""
            lines.append(f"  {json.dumps(name)}: {json.dumps(fd['routes'][name])}{sep}")
        lines.append("}}" + ("," if i < len(doc["formats"]) - 1 else ""))
    lines += ["}", "}"]
    with open(o["out"], "w") as fh:
        fh.write("\n".join(lines) + "\n")
    for fname, fd in doc["formats"].items():
        print(f"{fname} (day {fd['deadline_day']}):")
        for name, r in sorted(fd["routes"].items(), key=lambda kv: -kv[1]["wins"]):
            print(f"  {name:20} {r['wins']:2}/{r['runs']} ({r['lo']}-{r['hi']} %) median win day {r['median_win_day']}")


if __name__ == "__main__":
    if len(sys.argv) < 2 or sys.argv[1] not in ("run", "build"):
        sys.exit(__doc__)
    {"run": run, "build": build}[sys.argv[1]](sys.argv[2:])
